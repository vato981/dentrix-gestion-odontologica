    private void marcarNav(int activo) {
        JButton[] btns = {navInicio, navTriaje, navPacientes, navAgenda,
                navFicha, navCaja, navReportes, navConfig};
        for (int i = 0; i < btns.length; i++) {
            if (i == activo) {
                btns[i].setBackground(TEAL);
                btns[i].setForeground(Color.WHITE);
            } else {
                btns[i].setBackground(Color.WHITE);
                btns[i].setForeground(Color.DARK_GRAY);
            }
        }
    }

