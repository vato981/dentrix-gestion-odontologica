    private void onCargar(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_onCargar
        int sel = tblTurnos.getSelectedRow();
        if (sel < 0) {
            return;
        }
        lblPaciente.setText("Paciente: " + modelo().getValueAt(sel, 2));
        String hor = String.valueOf(modelo().getValueAt(sel, 0));
        for (int i = 0; i < cbHorario.getItemCount(); i++) {
            if (String.valueOf(cbHorario.getItemAt(i)).startsWith(hor.split(" ")[0])) {
                cbHorario.setSelectedIndex(i);
            }
        }
    }//GEN-LAST:event_onCargar

